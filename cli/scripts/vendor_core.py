"""Copy the pure upgrade planner core into the CLI package before building it.

`kubeastra upgrade` runs the planner in ``mcp/services/upgrade`` with the
deprecation maps in ``mcp/data/upgrades``. Both live outside ``cli/``, so a
wheel built from ``cli/`` alone shipped without them: the 0.2.x CLI worked
from a repo checkout (and in CI, which installs it editable) and failed for
everyone who installed it from PyPI.

This script copies them to ``cli/src/kubeastra/_vendor/`` keeping the same
relative layout (``services/upgrade`` next to ``data/upgrades``), because
``maps.py`` finds its data at ``parents[2] / "data" / "upgrades"``. The copy is
gitignored and regenerated on every build, so there is one source of truth.

Run it before ``python -m build``:

    python cli/scripts/vendor_core.py
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CORE_SRC = REPO / "mcp" / "services" / "upgrade"
DATA_SRC = REPO / "mcp" / "data" / "upgrades"
VENDOR = REPO / "cli" / "src" / "kubeastra" / "_vendor"

_HEADER = "# Generated by cli/scripts/vendor_core.py — do not edit; edit mcp/ instead.\n"


def vendor() -> list[Path]:
    for src in (CORE_SRC, DATA_SRC):
        if not src.is_dir():
            sys.exit(f"vendor_core: {src} not found — run from a KubeAstra checkout")

    shutil.rmtree(VENDOR, ignore_errors=True)
    core_dst = VENDOR / "services" / "upgrade"
    data_dst = VENDOR / "data" / "upgrades"
    core_dst.mkdir(parents=True)
    data_dst.mkdir(parents=True)

    # Package markers so `kubeastra._vendor.services.upgrade` imports, and so
    # setuptools' package discovery picks the copy up.
    (VENDOR / "__init__.py").write_text(_HEADER)
    (VENDOR / "services" / "__init__.py").write_text(_HEADER)

    written: list[Path] = []
    for f in sorted(CORE_SRC.glob("*.py")):
        shutil.copy2(f, core_dst / f.name)
        written.append(core_dst / f.name)
    for f in sorted(DATA_SRC.glob("*.yaml")):
        shutil.copy2(f, data_dst / f.name)
        written.append(data_dst / f.name)

    if not any(p.name == "__init__.py" for p in written):
        sys.exit("vendor_core: services/upgrade/__init__.py missing from the core")
    return written


if __name__ == "__main__":
    files = vendor()
    print(f"vendor_core: {len(files)} files -> {VENDOR.relative_to(REPO)}")
