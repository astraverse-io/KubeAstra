"""Copy the pure Pilot cores into the CLI package before building it.

`kubeastra upgrade` runs the planner in ``mcp/services/upgrade`` with the
deprecation maps in ``mcp/data/upgrades``. Both live outside ``cli/``, so a
wheel built from ``cli/`` alone shipped without them: the 0.2.x CLI worked
from a repo checkout (and in CI, which installs it editable) and failed for
everyone who installed it from PyPI.

``kubeastra resilience`` needs ``mcp/services/resilience`` + ``mcp/data/resilience``
the same way. This script copies them to ``cli/src/kubeastra/_vendor/`` keeping the same
relative layout (``services/upgrade`` next to ``data/upgrades``), because
``maps.py`` finds its data at ``parents[2] / "data" / "upgrades"``. The shared
manifest reader ``mcp/services/manifests.py`` goes along too: ``scan.py`` imports
it relatively (``from ..manifests import …``). The copy is
gitignored and regenerated on every build, so there is one source of truth.

Run it before ``python -m build``:

    python cli/scripts/vendor_core.py
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
MCP = REPO / "mcp"
# (core package under mcp/services, its data directory under mcp/data)
CORES = [("upgrade", "upgrades"), ("resilience", "resilience")]
SHARED_SRC = [MCP / "services" / "manifests.py"]
VENDOR = REPO / "cli" / "src" / "kubeastra" / "_vendor"

_HEADER = "# Generated by cli/scripts/vendor_core.py — do not edit; edit mcp/ instead.\n"


def vendor() -> list[Path]:
    sources = [MCP / "services" / core for core, _ in CORES] + [MCP / "data" / data for _, data in CORES]
    for src in sources:
        if not src.is_dir():
            sys.exit(f"vendor_core: {src} not found — run from a KubeAstra checkout")
    for f in SHARED_SRC:
        if not f.is_file():
            sys.exit(f"vendor_core: {f} not found — run from a KubeAstra checkout")

    shutil.rmtree(VENDOR, ignore_errors=True)
    (VENDOR / "services").mkdir(parents=True)
    # Package markers so `kubeastra._vendor.services.<core>` imports, and so
    # setuptools' package discovery picks the copy up.
    (VENDOR / "__init__.py").write_text(_HEADER)
    (VENDOR / "services" / "__init__.py").write_text(_HEADER)

    written: list[Path] = []
    for f in SHARED_SRC:
        shutil.copy2(f, VENDOR / "services" / f.name)
        written.append(VENDOR / "services" / f.name)
    for core, data in CORES:
        core_dst = VENDOR / "services" / core
        data_dst = VENDOR / "data" / data
        core_dst.mkdir(parents=True)
        data_dst.mkdir(parents=True)
        for f in sorted((MCP / "services" / core).glob("*.py")):
            shutil.copy2(f, core_dst / f.name)
            written.append(core_dst / f.name)
        for f in sorted((MCP / "data" / data).glob("*.yaml")):
            shutil.copy2(f, data_dst / f.name)
            written.append(data_dst / f.name)
        if not (core_dst / "__init__.py").is_file():
            sys.exit(f"vendor_core: services/{core}/__init__.py missing from the core")
    return written


if __name__ == "__main__":
    files = vendor()
    print(f"vendor_core: {len(files)} files -> {VENDOR.relative_to(REPO)}")
